/**
 * The zip to zone table's compact form (#4205), shared by the generator
 * (`scripts/generate-zip-zones.ts`) and pinned by `scripts/test-zip-zones.ts`, so the
 * encoding the generator writes and the decoder `src/lib/zip-zones/zip-zones.ts` reads
 * are tested as one pair.
 *
 * About 41,000 zips, but zones follow the first three digits almost everywhere, so:
 *
 *   - ZONES: the zone names, each written as one character of `ZONE_ALPHABET`;
 *   - PREFIXES: 1,000 characters, one per three digit prefix: its zone's character
 *     when every known zip under it shares one, `*` when they do not, `.` for a
 *     prefix with no known zip (refused, never guessed);
 *   - MIXED: for every zip under a `*` prefix, six characters (the zip and its zone's
 *     character), sorted, so a zip under a split prefix that the data does not know is
 *     refused rather than given its neighbours' majority;
 *   - STATES: the zone of each state whose every zip shares one, the only states whose
 *     two letter code may stand in for a zip.
 */
import { MIXED_PREFIX, NO_PREFIX, ZONE_ALPHABET } from "../../src/lib/zip-zones/zip-zones.ts";

export interface ZipZoneSource {
  zip: string;
  state: string;
  zone: string;
}

export interface CompactZipZones {
  zones: string[];
  prefixes: string;
  mixed: string;
  states: Record<string, string>;
}

export function compactTable(rows: readonly ZipZoneSource[]): CompactZipZones {
  const zones = [...new Set(rows.map((r) => r.zone))].sort();
  if (zones.length > ZONE_ALPHABET.length) throw new Error(`${zones.length} zones do not fit the ${ZONE_ALPHABET.length} character alphabet`);
  const char = (zone: string) => ZONE_ALPHABET[zones.indexOf(zone)];
  const byZip = new Map<string, string>();
  for (const r of rows) {
    // A zip listed twice with two zones is not a fact either row can state.
    const prior = byZip.get(r.zip);
    if (prior !== undefined && prior !== r.zone) throw new Error(`zip ${r.zip} is listed with two zones, ${prior} and ${r.zone}`);
    byZip.set(r.zip, r.zone);
  }
  const prefixZones = new Map<string, Set<string>>();
  for (const [zip, zone] of byZip) {
    const p = zip.slice(0, 3);
    const set = prefixZones.get(p) ?? new Set<string>();
    set.add(zone);
    prefixZones.set(p, set);
  }
  let prefixes = "";
  const mixedPrefixes = new Set<string>();
  for (let i = 0; i < 1000; i++) {
    const p = String(i).padStart(3, "0");
    const set = prefixZones.get(p);
    if (!set) prefixes += NO_PREFIX;
    else if (set.size === 1) prefixes += char([...set][0]);
    else {
      prefixes += MIXED_PREFIX;
      mixedPrefixes.add(p);
    }
  }
  const mixed = [...byZip]
    .filter(([zip]) => mixedPrefixes.has(zip.slice(0, 3)))
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([zip, zone]) => zip + char(zone))
    .join("");
  const stateZones = new Map<string, Set<string>>();
  for (const r of rows) {
    const set = stateZones.get(r.state) ?? new Set<string>();
    set.add(r.zone);
    stateZones.set(r.state, set);
  }
  const states: Record<string, string> = {};
  for (const [state, set] of [...stateZones].sort(([a], [b]) => (a < b ? -1 : 1))) {
    if (set.size === 1) states[state] = [...set][0];
  }
  return { zones, prefixes, mixed, states };
}

/** The generated module's source text, and the counts the generator reports. */
export function compactZipZones(rows: readonly ZipZoneSource[]): { source: string; mixedPrefixes: number; singleZoneStates: number } {
  const t = compactTable(rows);
  const mixedPrefixes = [...t.prefixes].filter((c) => c === MIXED_PREFIX).length;
  const chunk = (s: string, n: number) => (s.match(new RegExp(`.{1,${n}}`, "g")) ?? []).map((line) => `  ${JSON.stringify(line)}`).join(" +\n");
  const source = `// GENERATED by scripts/generate-zip-zones.ts from GeoNames (https://www.geonames.org),
// licensed under Creative Commons Attribution 4.0 (https://creativecommons.org/licenses/by/4.0/).
// Do not edit by hand: regenerate, then run scripts/test-zip-zones.ts. The encoding is
// described in scripts/lib/zip-zone-compact.ts and read by ./zip-zones.ts.
// ${rows.length} zips, ${t.zones.length} zones, ${mixedPrefixes} split prefixes.

export const ZIP_ZONE_NAMES: readonly string[] = ${JSON.stringify(t.zones)};

export const ZIP_ZONE_PREFIXES =
${chunk(t.prefixes, 100)};

export const ZIP_ZONE_MIXED =
${chunk(t.mixed, 96)};

export const STATE_ZONES: Readonly<Record<string, string>> = ${JSON.stringify(t.states, null, 2)};
`;
  return { source, mixedPrefixes, singleZoneStates: Object.keys(t.states).length };
}
