/**
 * Cloudflare data centres by the code a `cf-ray` header ends in (#3712), split into the
 * ones in North America and every other one, each with its city for the page.
 *
 * Why North America is the line: Slate's leads are in the United States, and a read the
 * latency canary makes through a colo on another continent times a route no lead takes
 * (2026-10-13: two of four pages entered at London and Dublin). The set is the whole
 * continent, Mexico, Central America and the Caribbean included, rather than only the
 * United States and Canada, because a colo counted as North America still pages: the
 * wider set errs toward paging, which is the harmless side.
 *
 * How it was drawn: every colo the source puts in Cloudflare's North America region,
 * plus the 6 it files under South America although their country is in Central
 * America or the Caribbean (GND, POS, PTY, SAP, SJO, TGU). Guyana (GEO) is in South America and
 * stays on the other list.
 *
 * Both halves are listed on purpose. A code on NEITHER list (a colo Cloudflare opened
 * after this snapshot, or a header that changed shape) is unrecognised, and the canary
 * judges that run exactly as it did before this existed, so a gap in the snapshot can
 * only ever cost a page, never hide one (L217, L648).
 *
 * Snapshot of 341 colos taken 2026-10-14 from github.com/Netrvin/cloudflare-colo-list
 * (DC-Colos.json), which mirrors Cloudflare's speed.cloudflare.com/locations feed with
 * its region and country per colo. Cloudflare's feed answered `{}` to a direct request
 * that day, so it could not be read first hand. Refresh it the same way when the canary
 * names an unrecognised colo.
 *
 * Imports nothing: the canary runs on bare node with no dependency install.
 */

